package com.securebank.lab.common;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.core.io.ClassPathResource;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * Serves the lab panel content.
 *
 * <p>The payload is generated by {@code scripts/sync-labs.py} from
 * {@code labs/labs.meta.yaml} and the real Java sources, so the "Affected Code" tab
 * always shows the current implementation.</p>
 */
@RestController
@RequestMapping("/api/labs")
public class LabsController {

    private final ObjectMapper mapper = new ObjectMapper();
    private volatile Map<String, Object> cache;

    @GetMapping
    public ResponseEntity<?> all() {
        return ResponseEntity.ok(load());
    }

    @GetMapping("/{id}")
    public ResponseEntity<?> one(@PathVariable int id) {
        Map<String, Object> payload = load();
        List<?> labs = (List<?>) payload.get("labs");
        for (Object item : labs) {
            Map<?, ?> lab = (Map<?, ?>) item;
            if (((Number) lab.get("id")).intValue() == id) {
                return ResponseEntity.ok(lab);
            }
        }
        return ResponseEntity.status(404).body(Map.of("error", "Lab not found"));
    }

    @SuppressWarnings("unchecked")
    private Map<String, Object> load() {
        Map<String, Object> current = cache;
        if (current != null) {
            return current;
        }
        synchronized (this) {
            if (cache != null) {
                return cache;
            }
            cache = read();
            return cache;
        }
    }

    private Map<String, Object> read() {
        try (InputStream in = new ClassPathResource("labs/labs.json").getInputStream()) {
            JsonNode node = mapper.readTree(in);
            return mapper.convertValue(node, LinkedHashMap.class);
        } catch (IOException e) {
            Map<String, Object> fallback = new LinkedHashMap<>();
            fallback.put("categories", new ArrayList<>());
            fallback.put("labs", new ArrayList<>());
            fallback.put("error", "labs.json has not been generated - run scripts/sync-labs.py");
            return fallback;
        }
    }

    /**
     * Returns the list of lab ids grouped by OWASP category.
     */
    @GetMapping("/categories")
    public ResponseEntity<?> categories() {
        Map<String, Object> payload = load();
        Object cats = payload.get("categories");
        List<?> list = cats instanceof List<?> l ? l : List.of();
        List<Map<String, Object>> out = new ArrayList<>();
        for (Object item : list) {
            Map<String, Object> map = new LinkedHashMap<>();
            map.put("code", ((Map<?, ?>) item).get("code"));
            map.put("name", ((Map<?, ?>) item).get("name"));
            map.put("labs", ((Map<?, ?>) item).get("labs"));
            out.add(map);
        }
        return ResponseEntity.ok(out);
    }

    /**
     * Returns the raw generated payload as text, for debugging the sync script.
     */
    @GetMapping(value = "/raw", produces = "text/plain;charset=UTF-8")
    public ResponseEntity<?> raw() {
        try (InputStream in = new ClassPathResource("labs/labs.json").getInputStream()) {
            return ResponseEntity.ok(new String(in.readAllBytes(), StandardCharsets.UTF_8));
        } catch (IOException e) {
            return ResponseEntity.status(404).body("labs.json not found");
        }
    }
}
